"""Render a reviewable Russian Markdown report from committed aggregate artifacts."""
import argparse
import json
import re
from pathlib import Path
from .data import sha256


def pct(value):
    return '—' if value is None else f'{100*value:.2f}%'


def num(value):
    return '—' if value is None else f'{value:,.2f}'.replace(',', ' ')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--artifacts', type=Path, default=Path(__file__).parent/'artifacts')
    parser.add_argument('--output', type=Path, default=Path(__file__).parent/'REPORT.md')
    args = parser.parse_args()
    def read(name):
        return json.loads((args.artifacts/name).read_text())
    selection, validation, evaluation, manifest, ablation = [read(name) for name in
        ('selection.json', 'validation.json', 'evaluation.json', 'manifest.json', 'ablation.json')]
    out = ['# Прогноз продаж v2: проверенные результаты', '',
        '**Порог WAPE ≤ 10% не подтверждён**.' if not evaluation['threshold_achieved_all_panels'] else '**Порог достигнут на перечисленных ретроспективных окнах; независимое подтверждение не получено.**', '',
        'Сравнение относится к неизменённым положительным отгрузкам: сумма количества по SKU за 28 календарных дней. '
        'Это оценка наблюдаемых продаж, а не восстановленного скрытого или «очищенного регулярного» спроса. '
        'Главная сопоставимая с v1 панель — Systeme Electric, Алматы, штуки. IEK дополнительно проверен отдельно по единицам.', '',
        '| Панель | Выбранный по validation метод | Validation WAPE | Повторная оценка WAPE | MAE на SKU × окно | Смещение |',
        '| --- | --- | ---: | ---: | ---: | ---: |']
    for panel, policy in selection['panels'].items():
        v = validation['panels'][panel]['candidates'][policy['selected']]['overall']
        e = evaluation['panels'][panel]['methods']['selected']['overall']
        out.append(f"| {panel} | `{policy['selected']}` | {pct(v['wape'])} | {pct(e['wape'])} | {num(e['mae'])} | {pct(e['bias'])} |")
    se = evaluation['panels']['SE__pieces']['methods']
    chosen, baseline = se['selected']['overall']['wape'], se['v1_baseline']['overall']['wape']
    out += ['', f"В сопоставимой панели SE baseline v1 воспроизведён: WAPE **{pct(baseline)}**. "
        f"Изменение выбранной v2: **{100*(chosen-baseline):+.2f} процентного пункта** "
        f"({100*(chosen/baseline-1):+.2f}% относительно ошибки baseline). "
        'Сохранённый отчёт v1 для CatBoost показывал 49,19%; его старые финальные веса не применялись к прошлым датам.', '',
        'Общий WAPE по всем единицам не рассчитывается. Штуки, метры и упаковки нельзя сложить в одну осмысленную цель. '
        'Объединение поставщиков внутри одинаковой единицы:', '',
        '| Единица | WAPE | MAE | Смещение | SKU × окна |', '| --- | ---: | ---: | ---: | ---: |']
    for unit, row in evaluation['by_unit'].items():
        m = row['overall']
        out.append(f"| {unit} | {pct(m['wape'])} | {num(m['mae'])} | {pct(m['bias'])} | {m['sku_windows']} |")
    out += ['', '## Протокол и даты', '',
        'Origin включён в историю. Цель — дни origin + 1 … origin + 28 включительно. '
        'Каждая обучающая метка полностью завершается не позже origin. Случайного разделения нет. '
        'Признаки и группы заново рассчитываются только по прошлой истории.', '',
        '| Роль | Origin | Период продаж |', '| --- | --- | --- |',
        '| Validation | 04.05.2026 | 05.05–01.06.2026 |',
        '| Validation | 01.06.2026 | 02.06–29.06.2026 |',
        '| Validation | 29.06.2026 | 30.06–27.07.2026 |',
        '| Ретроспективная повторная оценка | 27.07.2026 | 28.07–24.08.2026 |',
        '| Ретроспективная повторная оценка | 24.08.2026 | 25.08–21.09.2026 |', '',
        '**Последние два окна уже просматривались при разработке v1. Они не являются новым независимым тестом.** '
        'Параметры и смеси выбраны по суммарной абсолютной ошибке трёх validation-окон, отдельно по панели. '
        'Выбор затем зафиксирован; при повторной оценке модели переобучались на доступном прошлом, но параметры и правило выбора не менялись.', '',
        f"SHA-256 зафиксированного выбора: `{sha256(args.artifacts/'selection.json')}`. "
        f"Время фиксации: `{selection['frozen_at_utc']}`. Хеши исходных файлов записаны в `selection.json` и `validation.json`. "
        'Хеши реализации находятся в `implementation_sha256`.', '',
        '## Результаты каждого окна', '',
        '| Панель | Роль | Origin | WAPE | MAE | Смещение | Фактическое количество | SKU × окна |',
        '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |']
    for panel, policy in selection['panels'].items():
        for role, summary in [('validation', validation['panels'][panel]['candidates'][policy['selected']]),
                              ('повторная оценка', evaluation['panels'][panel]['methods']['selected'])]:
            for origin, m in summary['by_origin'].items():
                out.append(f"| {panel} | {role} | {origin} | {pct(m['wape'])} | {num(m['mae'])} | {pct(m['bias'])} | {num(m['actual_quantity'])} | {m['sku_windows']} |")
    out += ['', '## Сравнение методов', '',
        'Проверены 35 сезонных, постоянных и интервальных базовых правил, две ridge-регрессии и семь вариантов CatBoost '
        '(MAE, RMSE, Poisson; с масштабированием цели и без него; глубины 4–6; вариант без SKU). '
        'Дополнительно проверены четыре адаптивных селектора, 21 смесь CatBoost с baseline v1 и 135 выпуклых пар '
        'из девяти обучаемых моделей и годового среднего. Всего **204 кандидата на панель**, одна и та же сетка для всех панелей. '
        'Смеси используют фиксированные веса 0,25 / 0,5 / 0,75, выбранные по validation. '
        'Большой поиск по трём окнам повышает риск переобучения выбора; это не устраняется красивым средним WAPE.', '',
        '| Панель | Семейство | Лучший кандидат семейства на validation | WAPE |', '| --- | --- | --- | ---: |']
    families = {
        'сезонные и сглаживание': lambda n: n.startswith(('mean', 'median', 'year', 'monthly', 'ses_')) or n=='v1_baseline',
        'редкие продажи SBA/TSB': lambda n: n.startswith(('sba_', 'tsb_')),
        'регрессия': lambda n: n.startswith('ridge_'),
        'CatBoost': lambda n: n.startswith('cb_'),
        'адаптивный выбор по группе': lambda n: n=='adaptive_group',
        'адаптивный выбор по SKU': lambda n: n.startswith('adaptive_sku_'),
        'смеси': lambda n: n.startswith(('blend:', 'mix|'))}
    for panel, details in validation['panels'].items():
        candidates = details['candidates']
        for family, condition in families.items():
            best = min((n for n in candidates if condition(n)), key=lambda n: candidates[n]['overall']['absolute_error'])
            out.append(f"| {panel} | {family} | `{best}` | {pct(candidates[best]['overall']['wape'])} |")
    out += ['', 'Зафиксированные до evaluation альтернативы также оценены на исходных продажах. '
        'Следующая таблица не используется для повторного выбора. Лучший результат здесь — ретроспективное '
        'наблюдение, а не новая validation-оценка или независимое подтверждение.', '',
        '| Панель | Роль | Метод | WAPE на двух повторных окнах | MAE | Смещение |',
        '| --- | --- | --- | ---: | ---: | ---: |']
    for panel, policy in selection['panels'].items():
        for role, name in [('зафиксированный выбор', 'selected'), ('лучший одиночный ML на validation', policy['best_ml']),
                           ('лучший простой на validation', policy['best_simple']), ('лучший адаптивный на validation', policy['best_adaptive']),
                           ('baseline v1', 'v1_baseline'), ('диагностический выбор по группе', 'static_group_diagnostic')]:
            m = evaluation['panels'][panel]['methods'][name]['overall']
            out.append(f"| {panel} | {role} | `{policy['selected'] if name == 'selected' else name}` | {pct(m['wape'])} | {num(m['mae'])} | {pct(m['bias'])} |")
    out += ['', 'MAE/Poisson обучаются по исходным целям; масштабирование цели обратимо. '
        'При scaled MAE веса пропорциональны масштабу, чтобы оптимизация учитывала абсолютную ошибку в единицах. '
        'Ridge использует относительные признаки, L2 = 1 или 100. Для деревьев: 500 итераций, learning rate 0,04, '
        'L2 = 10, seed = 42, CPU, четыре потока. Годовое среднее — сумма последних 364 дней / 13.', '',
        '## Индивидуальный выбор и группы товаров', '',
        'Для адаптивных методов накоплены ошибки прошлых прогнозов, цель которых уже завершилась. '
        'Используется до 364 дней прошлых origin, половинный вес ошибок через 180 дней. '
        'Выбор по SKU сравнивается с выбором по группе; индивидуальные ошибки сглаживаются к групповым '
        'с силой 0, 3 или 10 эквивалентных прошлых окон. Ни одна текущая целевая продажа при выборе не используется.', '',
        'Группы формируются по прошлым продажам: new — менее 84 дней от первой наблюдаемой продажи; '
        'inactive — нет положительных продаж за 84 дня; intermittent — средний интервал между ненулевыми '
        'неделями за 168 дней ≥ 1,32; erratic — иначе CV² положительных недель ≥ 0,49; regular — остальные. '
        'ABC рассчитывается по прошлому годовому объёму: A — первые 80%, B — до 95%, C — остаток. '
        'Это аналитические группы продаж, не текущие закупочные категории поставщика.', '',
        '| Панель | Выбор по SKU/группе, лучший на validation | Validation WAPE | Повторная оценка WAPE |',
        '| --- | --- | ---: | ---: |']
    for panel, policy in selection['panels'].items():
        name = policy['best_adaptive']
        v = validation['panels'][panel]['candidates'][name]['overall']
        e = evaluation['panels'][panel]['methods'][name]['overall']
        out.append(f"| {panel} | `{name}` | {pct(v['wape'])} | {pct(e['wape'])} |")
    out += ['', 'Отдельно зафиксирована диагностическая таблица методов по группе, подобранная по всем validation-окнам. '
        'Её apparent validation score является ошибкой на данных подбора, а не честной оценкой будущего. '
        'Она применена к evaluation без изменения; результат находится в `static_group_diagnostic`. '
        'По её результату на evaluation финальный метод не переключался.', '',
        '| Панель | Группа | WAPE, повторная оценка | MAE | Смещение | Фактическое количество | SKU × окна |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: |']
    for panel, detail in evaluation['panels'].items():
        for group, m in detail['methods']['selected']['by_group'].items():
            out.append(f"| {panel} | {group} | {pct(m['wape'])} | {num(m['mae'])} | {pct(m['bias'])} | {num(m['actual_quantity'])} | {m['sku_windows']} |")
    out += ['', 'Все группы, включая ABC, нулевые фактические продажи и новые SKU, также приведены для каждого '
        'кандидата в JSON. Нулевой знаменатель даёт WAPE = null, но абсолютная ошибка не удаляется.', '',
        '## История 2024 года и аудит источников', '',
        'Детальная история начинается с 2025 года. Более ранние строки в динамике преимущественно являются '
        'возвратами/коррекциями, а не полной ежедневной историей. Помесячный 2024 год хранится отдельно. '
        'Он участвует в прошлогодних и двухлетних месячных признаках, а также в отношении сезонного профиля '
        'будущего горизонта к прошлым 84 дням. В этой прогнозной аппроксимации используются доли календарных '
        'месяцев; они никогда не записываются как реальные дневные наблюдения или обучающие цели.', '',
        'С 2025 года для месячных контекстных признаков агрегируется только детализация. '
        'Помесячная выгрузка за совпадающие периоды используется для сверки, не складывается с детализацией '
        'и не заменяет её. Полные месяцы доступны только после окончания месяца. '
        'Отрицательные месячные нетто-значения сохраняются в источнике; их отрицательный вклад ограничивается '
        'нулём только внутри неотрицательной прогнозной аппроксимации. Целевые продажи не обрезаются.', '',
        '| Поставщик | Положительных строк отгрузок | Отброшенных строк | Отрицательных строк | SKU в месячном отчёте | Расхождений SKU × месяц |',
        '| --- | ---: | ---: | ---: | ---: | ---: |']
    for supplier, audit in validation['sources'].items():
        t, m, r = audit['transactions'], audit['monthly'], audit['overlap_reconciliation']
        out.append(f"| {supplier} | {t['used_positive_invoice_rows']} | {t['excluded_rows']} | {t['negative_rows']} | {m['sku_count']} | {r['nonmatching_sku_months']} |")
    out += ['', 'Отбрасываются заголовки/итоги без даты и кода, нерасходные документы, неположительные или '
        'некорректные количества и неполная ранняя детализация до 2025 года. Возвраты не превращаются в продажи через abs(). '
        'Пустые месячные ячейки трактуются как нулевые продажи в формате этого отчёта — это явно указанное допущение. '
        'Пустые остатки так не интерпретируются; остатки вообще не используются в этих моделях.', '',
        'Ablation: тот же выбранный кандидат и те же параметры повторно обучены без 2024, только на validation. '
        'Эта диагностика не меняет зафиксированный выбор.', '',
        '| Панель | SKU с историей 2024 | Выбранный: с 2024 | Выбранный: без 2024 | Лучший одиночный ML: с 2024 | ML: без 2024 |',
        '| --- | ---: | ---: | ---: | ---: | ---: |']
    for panel, detail in ablation['panels'].items():
        policy = selection['panels'][panel]
        chosen_a, ml_a = detail['methods'][policy['selected']], detail['methods'][policy['best_ml']]
        out.append(f"| {panel} | {detail['monthly2024_matched_skus']} | {pct(chosen_a['with_2024']['overall']['wape'])} | {pct(chosen_a['without_2024']['overall']['wape'])} | {pct(ml_a['with_2024']['overall']['wape'])} | {pct(ml_a['without_2024']['overall']['wape'])} |")
    out += ['', '## Почему 10% не доказаны', '',
        'Ни лучший выбранный метод, ни перебор семейств не дают основания обещать этот порог. '
        'Это отрицательный результат проведённого эксперимента, не доказательство математической невозможности '
        'получить 10% другой моделью или с новыми источниками.', '',
        '| Панель | Origin | Доля абсолютной ошибки в 10 наиболее ошибочных SKU | Доля объёма у 10 крупнейших SKU | Неизвестных будущих SKU | Их фактический объём |',
        '| --- | --- | ---: | ---: | ---: | ---: |']
    for panel, detail in evaluation['panels'].items():
        for origin, d in detail['diagnostics'].items():
            out.append(f"| {panel} | {origin} | {pct(d['top10_share_absolute_error'])} | {pct(d['top10_share_volume'])} | {d['unseen_future_skus']} | {num(d['unseen_future_quantity'])} |")
    out += ['', '- Нет клиентских ID и подтверждённых проектов: причину крупных непредвиденных отгрузок определить нельзя. '
            'Такие отгрузки остаются в цели, а не удаляются ради WAPE.',
        '- Нет точных интервалов наличия: падение продаж нельзя уверенно отделить от stockout. '
            'Никакие дни stockout или потерянный спрос не выдумывались.',
        '- Месячная история — нетто-агрегаты, подробная цель — положительные отгрузки. В месячном файле нет явных колонок склада и единицы: связь по SKU предполагает сопоставимость с наблюдаемой в детализации единицей и складом. Расхождения источников '
            'не позволяют объявлять их взаимозаменяемыми без бухгалтерской сверки.',
        '- Нет времён загрузки и версий исправлений источника. Проверка воспроизводит доступность по дате события, '
            'но не доказывает, что позднейших исправлений в исторической выгрузке нет.',
        '- Отсутствие строк дневных продаж считается нулём наблюдаемых продаж при предположении полноты журнала с 2025 года. '
            'Это не доказательство отсутствия спроса. SKU, известные только из месячного отчёта без исторической единицы, '
            'не добавляются в дневной каталог. Будущие положительные продажи всех неизвестных SKU включаются в оценку с прогнозом 0.',
        '- Снимки текущих категорий, остатков, пути, MOQ и готовой сезонности не используются как исторические признаки. '
            'Новые известные на дату заказа клиентские обязательства могли бы помочь, но их нет в предоставленной истории.',
        '- Три validation-окна и два повторно просмотренных окна недостаточны для гарантии качества в производстве; '
            'нужен следующий ещё не просмотренный полный период. Последний день выгрузки 22.09.2026 исключён из целей и финального обучения.', '',
        '## Сохранённые веса и проверка', '',
        'Веса финально обучены на данных с завершившимися целями не позже 21.09.2026. '
        'Для каждой панели сохранены модели, необходимые выбранному методу, и лучший одиночный ML-кандидат. '
        'Если выигрывает статистический метод, он так и называется; наличие альтернативных весов не делает его ML. '
        'Загрузка проверяет SHA-256; команда infer действительно использует сохранённые файлы.', '',
        '| Панель | Файл | Последняя обучающая цель | SHA-256 |', '| --- | --- | --- | --- |']
    for panel, entry in manifest['panels'].items():
        for name, m in entry['models'].items():
            out.append(f"| {panel} | `{m['file']}` | {m['fit']['label_end_max']} | `{m['sha256']}` |")
    out += ['', 'Команды установки, полного повторения эксперимента и прогноза: [README.md](README.md), '
        'готовый сценарий: [reproduce.sh](reproduce.sh). '
        'Тесты проверяют изменение будущего без изменения прошлых признаков, точные границы 28 дней, '
        'неизменность реальной цели при добавлении 2024, раздельность источников, полноту окон, неизвестные SKU, '
        'отсечение будущих обучающих меток, запрет будущих ошибок в селекторе и точность загрузки весов/смеси. '
        'Метрики воспроизводимы при зафиксированных версиях и seed; бинарные файлы CatBoost могут иметь отличающиеся '
        'служебные метаданные времени/идентификатора при повторном обучении.', '',
        'Методологические источники: временные срезы — [Forecasting: Principles and Practice](https://otexts.com/fpp3/tscv.html); '
        'Croston — [Time series of counts](https://otexts.com/fpp3/counts.html); '
        'угасание редкого спроса и TSB — [Prestwich et al.](https://arxiv.org/abs/1409.1609); '
        'функции потерь — [документация CatBoost](https://catboost.ai/docs/en/concepts/loss-functions-regression). '
        'Численные результаты получены локально на партнёрских данных; внешние страницы не являются источником этих метрик.', '']
    rendered = re.sub(r'`([^`]+)`', lambda m: '`' + m.group(1).replace('|', r'\|') + '`', '\n'.join(out))
    args.output.write_text(rendered, encoding='utf-8')


if __name__ == '__main__':
    main()
