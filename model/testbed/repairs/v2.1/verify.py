"""Independent date-join replay and Decimal arithmetic; no production aggregate."""
import argparse
import csv
from datetime import date, timedelta
from decimal import Decimal
import hashlib
from itertools import product
import json
import math
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))
from model.testbed.adapters import call_external
from model.testbed.generator import PROTOCOL, generate

D = lambda value: Decimal(str(value))


def oracle(rows):
    result = {"rows": len(rows), "failed_rows": sum(r["error"] is not None for r in rows),
              "zero_realized_rows": sum(r["realized_regular_quantity"] == 0 for r in rows)}
    for name in ("realized_regular_quantity", "expected_regular_quantity", "project_quantity"):
        result[name] = float(sum((D(r[name]) for r in rows), Decimal(0)))
    for label, target, daily in (("realized", "realized_regular_quantity", "daily_absolute_error"),
                                  ("expectation", "expected_regular_quantity", "daily_absolute_error_expectation")):
        denominator = sum((D(r[target]) for r in rows), Decimal(0))
        absolute = sum((abs(D(r["forecast_quantity"]) - D(r[target])) for r in rows), Decimal(0))
        signed = sum((D(r["forecast_quantity"]) - D(r[target]) for r in rows), Decimal(0))
        daily_error = sum((D(r[daily]) for r in rows), Decimal(0))
        result["absolute_error_" + label] = float(absolute)
        result["wape_" + label] = float(absolute / denominator) if denominator else None
        result["bias_" + label] = float(signed / denominator) if denominator else None
        result["daily_wape_" + label] = float(daily_error / denominator) if denominator else None
        result["mae_" + label] = float(absolute / len(rows)) if rows else None
    return result


def verify(folder):
    report = json.loads((folder / "report.json").read_text())
    rows = report["rows"]
    assertions = 0

    def check(ok, message):
        nonlocal assertions
        if not ok:
            raise AssertionError(message)
        assertions += 1

    def close(actual, expected, message):
        check(actual is None if expected is None else isinstance(actual, (int, float)) and
              math.isclose(actual, expected, rel_tol=1e-12, abs_tol=1e-8), message)

    def check_metrics(actual, selected, label):
        expected = oracle(selected)
        for name, value in expected.items():
            if not name.startswith("mae_"):
                close(actual[name], value, label + "/" + name)
        check(not actual["numerical_failure"] and not actual["numerical_errors"], label + "/numerical state")
        return expected

    root = Path(__file__).resolve().parents[2]
    sources = sorted(root.rglob("*.py")) + [root / "protocol.json", root / "fixtures/business_cases.json"]
    check(report["source_hashes"] == {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
          "report was generated by current source files")
    indexed = {(r["seed"], r["scenario"], r["origin"], r["sku"]): r for r in rows}
    expected_keys = set(product(report["seeds"], PROTOCOL["scenarios"], PROTOCOL["origins"],
                                [f"SKU-{i+1:03d}" for i in range(PROTOCOL["items_per_case"])]))
    check(set(indexed) == expected_keys and len(indexed) == len(rows), "all cases retained, unique rows")
    check(not any(r["error"] for r in rows), "no failed predictions in this successful replay")
    for seed, scenario, origin in product(report["seeds"], PROTOCOL["scenarios"], PROTOCOL["origins"]):
        case = generate(scenario, seed, origin)
        prediction = call_external(report["adapter"], case.observed)
        public_hash = hashlib.sha256(json.dumps(case.observed, sort_keys=True).encode()).hexdigest()
        dates = [(date.fromisoformat(origin) + timedelta(days=i)).isoformat()
                 for i in range(1, PROTOCOL["horizon_days"] + 1)]
        for sku, values in prediction.items():
            row = indexed[seed, scenario, origin, sku]
            truth, projects = case.truth[sku], case.projects[sku]
            y = dict(zip(truth["dates"], truth["regular_realized"], strict=True))
            mu = dict(zip(truth["dates"], truth["regular_expectation"], strict=True))
            p = dict(zip(projects["dates"], projects["one_off_quantity"], strict=True))
            expected = {"forecast_quantity": math.fsum(values),
                        "realized_regular_quantity": math.fsum(y[d] for d in dates),
                        "expected_regular_quantity": math.fsum(mu[d] for d in dates),
                        "project_quantity": math.fsum(p[d] for d in dates),
                        "daily_absolute_error": math.fsum(abs(v-y[d]) for v, d in zip(values, dates, strict=True)),
                        "daily_absolute_error_expectation": math.fsum(abs(v-mu[d]) for v, d in zip(values, dates, strict=True))}
            for name, value in expected.items():
                close(row[name], value, str((seed, scenario, origin, sku, name)))
            check(row["input_sha256"] == public_hash, "public packet hash")
            check(row["unit"] == "шт", "common physical unit")
            check(abs(row["forecast_quantity"]-row["realized_regular_quantity"]) <= row["daily_absolute_error"]+1e-8,
                  "daily errors cannot be smaller than horizon error")
    overall = check_metrics(report["overall"], rows, "overall")
    for field in ("seed", "scenario", "origin", "unit"):
        check(set(report["groups"][field]) == {str(r[field]) for r in rows}, field + " group coverage")
        for value, actual in report["groups"][field].items():
            check_metrics(actual, [r for r in rows if str(r[field]) == value], field + "/" + value)
    check(set(report["groups"]["scenario_seed"]) == {f"{r['scenario']}/{r['seed']}" for r in rows}, "scenario/seed coverage")
    for value, actual in report["groups"]["scenario_seed"].items():
        check_metrics(actual, [r for r in rows if f"{r['scenario']}/{r['seed']}" == value], value)
    with (folder / "rows.csv").open(newline="") as handle:
        check(list(csv.DictReader(handle)) == [{k: "" if v is None else str(v) for k, v in r.items()} for r in rows], "CSV exact rows")
    check(report["forecast_target_met"] == (overall["wape_realized"] <= .1), "target flag uses realized WAPE")
    for name in ("business", "paired_project_checks"):
        check(report[name]["passed"] == sum(c["passed"] for c in report[name]["cases"]), name + " pass count")
        check(report[name]["total"] == len(report[name]["cases"]), name + " total count")
    return {"report": str(folder), "assertions_passed": assertions, "rows_replayed": len(rows),
            "daily_predictions_replayed": len(rows)*PROTOCOL["horizon_days"], "independent_decimal_metrics": overall,
            "hashes": {name: hashlib.sha256((folder/name).read_bytes()).hexdigest()
                       for name in ("report.json", "report.md", "rows.csv")}}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report-dir", action="append", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    results = [verify(Path(folder)) for folder in args.report_dir]
    Path(args.output).write_text(json.dumps({"results": results, "method": "independent date joins and Decimal ratios; no aggregate import"},
                                          ensure_ascii=False, allow_nan=False, indent=2) + "\n")
    print(json.dumps({"reports_verified": len(results), "rows_replayed": sum(r["rows_replayed"] for r in results),
                      "assertions_passed": sum(r["assertions_passed"] for r in results)}))
